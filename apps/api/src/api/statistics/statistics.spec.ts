import { ageOf } from './statistics.service';

/** Дати в базі — колонки `date`, тобто опівніч UTC. Рахуємо в тих самих координатах. */
const day = (value: string) => new Date(`${value}T00:00:00.000Z`);

describe('ageOf', () => {
  it('рахує повні роки, коли день народження вже був', () => {
    expect(ageOf(day('1990-03-10'), day('2026-10-01'))).toBe(36);
  });

  it('не додає рік наперед, коли день народження ще попереду', () => {
    expect(ageOf(day('1990-12-10'), day('2026-10-01'))).toBe(35);
  });

  it('додає рік у сам день народження', () => {
    expect(ageOf(day('1990-10-01'), day('2026-10-01'))).toBe(36);
  });

  it('не додає рік напередодні', () => {
    expect(ageOf(day('1990-10-02'), day('2026-10-01'))).toBe(35);
  });

  it('тримає 29 лютого в невисокосному році до 1 березня', () => {
    expect(ageOf(day('2000-02-29'), day('2026-02-28'))).toBe(25);
    expect(ageOf(day('2000-02-29'), day('2026-03-01'))).toBe(26);
  });

  it('віддає нуль для немовляти', () => {
    expect(ageOf(day('2026-09-01'), day('2026-10-01'))).toBe(0);
  });
});
