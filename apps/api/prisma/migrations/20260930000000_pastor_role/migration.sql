-- Роль «пастор»: відкриває пасторський шар по всіх, кого користувач і так бачить.
--
-- До цього пасторський шар відкривала роль адміністратора — єдиний виняток із
-- правила «шар дає опіка». Виняток виник тому, що в одній ролі були злиті дві
-- різні людини: пастор, якому цей шар потрібен по суті служіння, і адміністратор
-- спільноти, який веде структуру. Тепер вони розведені.
--
-- Саме значення enum додаємо окремою міграцією від його використання: Postgres
-- не дає користуватися свіжим значенням у тій самій транзакції.

ALTER TYPE "roles" ADD VALUE IF NOT EXISTS 'PASTOR';
